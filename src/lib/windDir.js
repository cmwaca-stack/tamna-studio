// 풍향: 기상청은 "바람이 불어 오는 방향"(도, 북=0, 시계 방향)을 줘요. 예) 67° = 북동쪽에서 불어 와서 남서쪽으로 불어 가요.
const NAMES = ['북', '북북동', '북동', '동북동', '동', '동남동', '남동', '남남동', '남', '남남서', '남서', '서남서', '서', '서북서', '북서', '북북서']
export const windName = (deg) => (Number.isFinite(deg) ? `${NAMES[Math.round((((deg % 360) + 360) % 360) / 22.5) % 16]}풍` : '')
// 화살표(위쪽을 가리키는 그림)를 돌릴 각도: 바람이 불어 가는 쪽 = 불어 오는 방향의 반대
export const blowAngle = (deg) => (((deg % 360) + 360) % 360 + 180) % 360
